const RTL = new Set(["ar", "he", "fa", "ur"]);
const base = (code: string) => code.toLowerCase().split("-")[0];

/** The copy for a language, falling back to English per line. */
export const guestCopy = (code: string) => {
  const c = { ...en, ...(COPY[base(code)] ?? {}) };
  return { t: (k: GuestKey) => c[k], lang: COPY[base(code)] ? base(code) : "en", dir: (RTL.has(base(code)) && COPY[base(code)] ? "rtl" : "ltr") as "rtl" | "ltr" };
};

/** The first of the reader's languages (`navigator.languages`, best first) that is one of `codes`. */
export function browserLanguage(codes: readonly string[], asked: readonly string[]): string | undefined {
  for (const l of asked) {
    const hit = codes.find((c) => c.toLowerCase() === l.toLowerCase()) ?? codes.find((c) => base(c) === base(l));
    if (hit) return hit;
  }
}
